    public static List<String> parseThemes(String themesInput) {
        if (themesInput == null || themesInput.isEmpty()) {
            return Collections.singletonList("DUMMYUFT");
        }
        return Arrays.stream(themesInput.split(","))
                .map(String::trim)
                .map(THEME_MAP::get)
                .filter(Objects::nonNull)
                .collect(Collectors.toList());
    }
